"""Organize verified findings into a report, then review every generated paragraph.

The model supplies no URLs. References are IDs of retained findings, and rendering adds
their source links in code. A missing finding or unsupported rewrite rejects the draft;
the report stage keeps its evidence-backed findings view instead.
"""

import json
import logging
import re
from typing import Any

from langchain_core.messages import HumanMessage
from pydantic import Field, ValidationError, model_validator

from contextforge.core.context.prompts import load_prompt, prompt_version
from contextforge.core.entities import Entity
from contextforge.core.entities.message import Claim, ReportBody
from contextforge.core.entities.model_call import Stage
from contextforge.core.models.base import ModelRequest
from contextforge.core.models.errors import ModelError
from contextforge.core.state import RequestState
from contextforge.core.values import LocatorKind
from contextforge.worker.dependencies import WorkerDependencies
from contextforge.worker.stages.review import review_statement_support

logger = logging.getLogger(__name__)


class ResearchParagraph(Entity):
    text: str = Field(min_length=1, max_length=1600)
    claim_ids: list[str] = Field(min_length=1, max_length=12)


class ResearchSection(Entity):
    heading: str = Field(min_length=1, max_length=150)
    paragraphs: list[ResearchParagraph] = Field(min_length=1, max_length=8)


class ResearchDraft(Entity):
    sections: list[ResearchSection] = Field(min_length=1, max_length=8)

    @model_validator(mode="after")
    def bounded(self) -> "ResearchDraft":
        if sum(len(section.paragraphs) for section in self.sections) > 20:
            raise ValueError("a research draft has at most 20 paragraphs")
        return self


def compose_research(
    request_state: RequestState, body: ReportBody, worker_dependencies: WorkerDependencies
) -> str | None:
    """A fully covered, support-reviewed narrative, or None for the findings fallback."""
    if not body.claims:
        return None
    try:
        response = worker_dependencies.model_for(
            request_state["request_message_id"], memory_version=request_state["memory"]["version"]
        ).invoke(
            ModelRequest(
                stage=Stage.REPORT,
                model=worker_dependencies.model_id(Stage.REPORT),
                system=[load_prompt(prompt_version(Stage.REPORT))],
                messages=[
                    HumanMessage(
                        json.dumps(
                            {
                                "question": request_state["goal"],
                                "findings": [
                                    {"id": c.claim_id, "text": c.text} for c in body.claims
                                ],
                                "gaps": body.uncertainties,
                            },
                            ensure_ascii=False,
                        )
                    )
                ],
                output_schema=ResearchDraft,
                max_tokens=4000,
            )
        )
        draft = ResearchDraft.model_validate(response.structured)
    except (ModelError, ValidationError) as exc:
        logger.warning("research draft unavailable: %s", type(exc).__name__)
        return None
    claims = {c.claim_id: c for c in body.claims}
    packets = _review_packets(draft, claims)
    if packets is None:
        return None
    verdicts = review_statement_support(request_state, packets, worker_dependencies)
    if any(p["id"] not in verdicts or verdicts[p["id"]].verdict != "supported" for p in packets):
        logger.warning("research draft rejected: a heading or paragraph lacks support")
        return None
    blocks = []
    for section in draft.sections:
        paragraphs = []
        for paragraph in section.paragraphs:
            refs = [claims[i] for i in dict.fromkeys(paragraph.claim_ids)]
            paragraphs.append(f"{paragraph.text.strip()} {source_links(refs)}")
        heading = f"## {_heading(section.heading)}\n\n" if len(body.claims) > 3 else ""
        blocks.append(heading + "\n\n".join(paragraphs))
    return "\n\n".join(blocks)


def _review_packets(draft: ResearchDraft, claims: dict[str, Claim]) -> list[dict[str, Any]] | None:
    used: set[str] = set()
    packets = []
    for i, section in enumerate(draft.sections):
        section_ids = {c for p in section.paragraphs for c in p.claim_ids}
        if not section_ids <= claims.keys():
            return None
        texts = [section.heading, *(p.text for p in section.paragraphs)]
        # Citation URLs are rendered from evidence, never generated by the writer.
        if any(re.search(r"https?://|\]\(|<[^>]*>", text) for text in texts):
            return None
        used.update(section_ids)
        packets.append(
            {
                "id": f"heading-{i}",
                "text": section.heading,
                "evidence": [{"text": claims[c].text} for c in sorted(section_ids)],
            }
        )
        for j, paragraph in enumerate(section.paragraphs):
            packets.append(
                {
                    "id": f"paragraph-{i}-{j}",
                    "text": paragraph.text,
                    "evidence": [{"text": claims[c].text} for c in paragraph.claim_ids],
                }
            )
    # A polished draft cannot silently drop a finding that survived review.
    return packets if used == claims.keys() else None


def source_links(claims: list[Claim]) -> str:
    urls = dict.fromkeys(
        ref.locator.value
        for claim in claims
        for ref in claim.evidence_refs
        if ref.locator.kind == LocatorKind.URL
    )
    return " ".join(f"[source]({url})" for url in urls)


def _heading(text: str) -> str:
    return " ".join(text.split()).lstrip("# ")
